def camel(k):
    return CAMEL.get(k, k)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


# ---------------- CSS (tones per state and theme) ----------------

def tone_vars(style, theme, state):
    p, out = style["prefix"], []
    for tone in style["tones"]:
        try:
            c = palette_color(style, theme, state, tone)
        except SourceError:
            continue
        if c["kind"] == "gradient":
            for i, st in enumerate(c["stops"]):
                out.append("--%s-%s-%d: %s; --%s-%s-%d-opacity: %s;" % (p, tone, i, st["hex"], p, tone, i, fmt(st["opacity"])))
        else:
            val = "var(--%s, %s)" % (c["token"].lstrip("-"), c["hex"]) if c.get("token") else c["hex"]
            out.append("--%s-%s: %s; --%s-%s-opacity: %s;" % (p, tone, val, p, tone, fmt(c["opacity"])))
    return " ".join(out)


def build_css(style, scope=None, dark_selectors=None, dark_mode=None):
    dark_selectors = dark_selectors or style.get("darkSelector") or [".dark", '[data-theme="dark"]']
    if isinstance(dark_selectors, str):
        dark_selectors = [dark_selectors]
    dark_mode = dark_mode or style.get("darkMode", "class")
    pre = (scope + " ") if scope else ""
    root = scope or ":root"

    def rule(sels, body):
        return ":where(%s) { %s }" % (", ".join(sels), body)

    def block(theme, dark_prefixes):
        lines = []
        if dark_prefixes is None:
            lines.append(rule([root], tone_vars(style, theme, "default")))
            ctx = [pre]
        else:
            lines.append(rule([pre + d for d in dark_prefixes], tone_vars(style, theme, "default")))
            ctx = [pre + d + " " for d in dark_prefixes]
        for state, sels in (("hover", HOVER_SEL), ("active", ACTIVE_SEL), ("disabled", DISABLED_SEL)):
            lines.append(rule([c + s for c in ctx for s in sels], tone_vars(style, theme, state)))
        return lines

    out = ["/* Icon tones per state and theme. Generated by generate-icons; edit icon-style.json, not this file. */"]
    out += block("light", None)
    if "dark" in style["palette"]:
        if dark_mode in ("class", "both"):
            out += block("dark", dark_selectors)
        if dark_mode in ("media", "both") and not scope:
            out.append("@media (prefers-color-scheme: dark) {")
            out += ["  " + line for line in block("dark", None)]
            out.append("}")
    return "\n".join(out) + "\n"


# ---------------- framework backends ----------------

def react_node(n, style, gid_expr):
    attrs, css = paint_props(n, style, "vars", gid=lambda t: "@@%s@@" % t)
    parts = ['%s="%s"' % (k, v) for k, v in n["geom"].items()]
    for k, v in attrs.items():
        if "@@" in v:
            tone = v.split("@@")[1]
            parts.append("%s={`url(#${id}-%s)`}" % (camel(k), tone))
        else:
            parts.append('%s="%s"' % (camel(k), v))
    if css:
        parts.append("style={{ %s }}" % ", ".join('%s: "%s"' % (camel(k), v) for k, v in css.items()))
    return "<%s %s />" % (n["tag"], " ".join(parts))


def react_defs(style, nodes):
    defs = gradient_defs(style, nodes, "vars", gid=lambda t: t)
    if not defs:
        return []
    out = ["<defs>"]
    for tone, x1, y1, x2, y2, stops in defs:
        out.append('  <linearGradient id={`${id}-%s`} x1="%s" y1="%s" x2="%s" y2="%s">' % (tone, x1, y1, x2, y2))
        for off, color, op in stops:
            out.append('    <stop offset="%s" style={{ stopColor: "%s", stopOpacity: "%s" }} />' % (off, color, op))
        out.append("  </linearGradient>")
    out.append("</defs>")
    return out


def gen_react(icons, style, out):
    g = fmt(style["grid"])
    rendering = '\n        shapeRendering="%s"' % style["rendering"] if style.get("rendering") else ""
    write(os.path.join(out, "src", "create-icon.tsx"), REACT_BASE.replace("__GRID__", g).replace("__RENDERING__", rendering))
    for icon in icons:
        nodes = icon_nodes(icon, style)
        body = react_defs(style, nodes) + [react_node(n, style, None) for n in nodes]
        uses_id = any("${id}" in b for b in body)
        cname = component_name(icon["name"])
        text = ('import { createIcon } from "../create-icon"\n\n'
                "/** %s */\nexport const %s = createIcon(\"%s\", (%s) => (\n  <>\n%s\n  </>\n))\n\nexport default %s\n"
                % (icon["label"], cname, cname, "id" if uses_id else "", "\n".join("    " + b for b in body), cname))
        write(os.path.join(out, "src", "icons", icon["name"] + ".tsx"), text)
    return "tsx"


def vue_node(n, style):
    attrs, css = paint_props(n, style, "vars", gid=lambda t: "@@%s@@" % t)
    props = ["%s: %s" % (json.dumps(k), json.dumps(v)) for k, v in n["geom"].items()]
    for k, v in attrs.items():
        if "@@" in v:
            props.append("%s: `url(#${id}-%s)`" % (json.dumps(k), v.split("@@")[1]))
        else:
            props.append("%s: %s" % (json.dumps(k), json.dumps(v)))
    if css:
        props.append('style: %s' % json.dumps(";".join("%s:%s" % kv for kv in css.items())))
    return 'h("%s", { %s })' % (n["tag"], ", ".join(props))


def gen_vue(icons, style, out):
    g = fmt(style["grid"])
    rendering = ', "shape-rendering": "%s"' % style["rendering"] if style.get("rendering") else ""
    write(os.path.join(out, "src", "create-icon.ts"), VUE_BASE.replace("__GRID__", g).replace("__RENDERING__", rendering))
    for icon in icons:
        nodes = icon_nodes(icon, style)
        items, grads = [], []
        for tone, x1, y1, x2, y2, stops in gradient_defs(style, nodes, "vars", gid=lambda t: t):
            st = ", ".join('h("stop", { offset: "%s", style: "stop-color:%s;stop-opacity:%s" })' % s for s in stops)
            grads.append('h("linearGradient", { id: `${id}-%s`, x1: "%s", y1: "%s", x2: "%s", y2: "%s" }, [%s])'
                         % (tone, x1, y1, x2, y2, st))
        if grads:
            items.append('h("defs", [%s])' % ", ".join(grads))
        items += [vue_node(n, style) for n in nodes]
        uses_id = any("${id}" in i for i in items)
        cname = component_name(icon["name"])
        text = ('import { h } from "vue"\nimport { createIcon } from "../create-icon"\n\n'
                "/** %s */\nexport const %s = createIcon(\"%s\", (%s) => [\n%s,\n])\n\nexport default %s\n"
                % (icon["label"], cname, cname, "id" if uses_id else "", ",\n".join("  " + i for i in items), cname))
        write(os.path.join(out, "src", "icons", icon["name"] + ".ts"), text)
    return "ts"


def gen_svelte(icons, style, out):
    g = fmt(style["grid"])
    rendering = ' shape-rendering="%s"' % style["rendering"] if style.get("rendering") else ""
    for icon in icons:
        nodes = icon_nodes(icon, style)
        body = []
        grads = ['<linearGradient id="{id}-%s" x1="%s" y1="%s" x2="%s" y2="%s">%s</linearGradient>' % (
            tone, x1, y1, x2, y2, "".join('<stop offset="%s" style="stop-color:%s;stop-opacity:%s" />' % s for s in stops))
            for tone, x1, y1, x2, y2, stops in gradient_defs(style, nodes, "vars", gid=lambda t: t)]
        if grads:
            body.append("<defs>%s</defs>" % "".join(grads))
        for n in nodes:
            attrs, css = paint_props(n, style, "vars", gid=lambda t: "{id}-" + t)
            parts = ['%s="%s"' % kv for kv in n["geom"].items()] + ['%s="%s"' % kv for kv in attrs.items()]
            if css:
                parts.append('style="%s"' % ";".join("%s:%s" % kv for kv in css.items()))
            body.append("<%s %s />" % (n["tag"], " ".join(parts)))
        text = SVELTE_ICON.replace("__GRID__", g).replace("__RENDERING__", rendering).replace(
            "__LABEL__", icon["label"]).replace("__BODY__", "\n  ".join(body))
        write(os.path.join(out, "src", "icons", icon["name"] + ".svelte"), text)
    return "svelte"


def gen_react_native(icons, style, out):
    g = fmt(style["grid"])
    tones = list(style["tones"])
    palette = {}
    for theme in style["palette"]:
        palette[theme] = {}
        for state in STATES:
            palette[theme][state] = {}
            for tone in tones:
                try:
                    c = palette_color(style, theme, state, tone)
                except SourceError:
                    continue
                palette[theme][state][tone] = c["stops"][0]["hex"] if c["kind"] == "gradient" else c["hex"]
    fallback_op = {t: tone_fallback(style, t)[1] for t in tones}
    base = (RN_BASE.replace("__GRID__", g)
            .replace("__TONES__", " | ".join(json.dumps(t) for t in tones))
            .replace("__PALETTE__", json.dumps(palette, indent=2))
            .replace("__FALLBACK_OPACITY__", json.dumps(fallback_op)))
    write(os.path.join(out, "src", "create-icon.tsx"), base)
    for icon in icons:
        nodes = icon_nodes(icon, style)
        used = {"Svg"}
        body = []
        defs = gradient_defs(style, nodes, "hex", gid=lambda t: "%s-%s" % (icon["name"], t))
        if defs:
            used |= {"Defs", "LinearGradient", "Stop"}
            body.append("<Defs>")
            for tone, x1, y1, x2, y2, stops in defs:
                body.append('  <LinearGradient id="%s" x1="%s" y1="%s" x2="%s" y2="%s">' % (tone, x1, y1, x2, y2))
                for off, color, op in stops:
                    body.append('    <Stop offset="%s" stopColor="%s" stopOpacity={%s} />' % (off, color, op))
                body.append("  </LinearGradient>")
            body.append("</Defs>")
        grad_tones = {d[0][len(icon["name"]) + 1:] for d in defs}
        for n in nodes:
            tag = RN_TAGS[n["tag"]]
            used.add(tag)
            attrs, _ = paint_props(n, style, "hex", gid=lambda t: t)
            kind = n["paint"]
            parts = ['%s="%s"' % kv for kv in n["geom"].items()]
            for k, v in attrs.items():
                if k in (kind, kind + "-opacity"):
                    continue
                parts.append('%s="%s"' % (camel(k), v))
            if n["tone"] in grad_tones:
                parts.append('%s="url(#%s-%s)"' % (kind, icon["name"], n["tone"]))
            else:
                parts.append('%s={t("%s").color} %sOpacity={t("%s").opacity}' % (kind, n["tone"], kind, n["tone"]))
            body.append("<%s %s />" % (tag, " ".join(parts)))
        cname = component_name(icon["name"])
        imports = sorted(used - {"Svg"})
        arg = "t" if any("{t(" in b for b in body) else ""
        text = ('import { %s } from "react-native-svg"\nimport { createIcon } from "../create-icon"\n\n'
                "/** %s */\nexport const %s = createIcon(\"%s\", (%s) => (\n  <>\n%s\n  </>\n))\n\nexport default %s\n"
                % (", ".join(imports), icon["label"], cname, cname, arg, "\n".join("    " + b for b in body), cname))
        write(os.path.join(out, "src", "icons", icon["name"] + ".tsx"), text)
    return "tsx"


def gen_index(icons, out, framework, ext):
    if framework == "svg":
        return
    lines = []
    for icon in icons:
        cname = component_name(icon["name"])
        if framework == "svelte":
            lines.append('export { default as %s } from "./icons/%s.svelte"' % (cname, icon["name"]))
        else:
            lines.append('export { %s } from "./icons/%s"' % (cname, icon["name"]))
    if framework in ("react", "react-native"):
        lines.append('export { createIcon } from "./create-icon"')
        lines.append('export type { IconProps, Icon } from "./create-icon"')
    if framework == "react-native":
        lines.append('export { palette } from "./create-icon"')
    if framework == "vue":
        lines.append('export { createIcon } from "./create-icon"')
    write(os.path.join(out, "src", "index.ts"), "\n".join(lines) + "\n")


def gen_package_json(src, style, out, framework, ext, name):
    existing = os.path.join(out, "package.json")
    if os.path.exists(existing):
        return  # never overwrite a package.json the project already owns
    pkg = {"name": name, "version": (src.get("package") or {}).get("version", "0.1.0"), "private": True,
           "description": "Icon library generated with generate-icons (%s style)." % style.get("name", "custom"),
           "sideEffects": ["*.css"], "files": ["src", "svg", "sprite.svg", "icons.css", "manifest.json"]}
    exports = {"./icons.css": "./icons.css", "./sprite.svg": "./sprite.svg", "./svg/*": "./svg/*",
               "./manifest.json": "./manifest.json"}
    peers = {"react": {"react": ">=18"}, "react-native": {"react": ">=18", "react-native-svg": ">=13"},
             "vue": {"vue": ">=3.5"}, "svelte": {"svelte": ">=5.20"}}.get(framework)
    if framework != "svg":
        exports = dict({".": "./src/index.ts", "./icons/*": "./src/icons/*.%s" % ext}, **exports)
        pkg["main"] = "./src/index.ts"
        pkg["types"] = "./src/index.ts"
        if framework == "svelte":
            pkg["svelte"] = "./src/index.ts"
    pkg["exports"] = exports
    if peers:
        pkg["peerDependencies"] = peers
    write(existing, json.dumps(pkg, indent=2) + "\n")


