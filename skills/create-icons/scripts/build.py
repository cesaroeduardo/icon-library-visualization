def use(sid, size, state=None, grid=24):
    st = ' data-icon-state="%s"' % state if state and state != "default" else ""
    return '<svg width="%s" height="%s" viewBox="0 0 %s %s" aria-hidden="true"%s><use href="#%s"/></svg>' % (
        size, size, fmt(grid), fmt(grid), st, sid)


def state_cells(sid, style):
    sizes = sorted(set(style["sizes"]) | {16, 24})
    cells = ['<div class="cell">%s%s</div>' % (use(sid, 24, s, style["grid"]), s) for s in STATES]
    cells.append('<div class="sep"></div>')
    cells += ['<div class="cell">%s%s</div>' % (use(sid, z, None, style["grid"]), z) for z in sizes]
    return "".join(cells)


