def build_sprite(icons, style, prefix="", data_tone=False, mode="vars"):
    g = fmt(style["grid"])
    syms = []
    for icon in icons:
        sid = prefix + icon["name"]
        syms.append('<symbol id="%s" viewBox="0 0 %s %s">%s</symbol>' % (
            sid, g, g, svg_inner(icon, style, mode, id_prefix=sid, data_tone=data_tone)))
    return syms


def strip_svg(text):
    text = re.sub(r"<\?xml[^>]*>|<!DOCTYPE[^>]*>|<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"<script.*?</script>", "", text, flags=re.S | re.I)
    text = re.sub(r"\son\w+=\"[^\"]*\"", "", text)
    text = re.sub(r"(<svg\b[^>]*?)\s(width|height)=\"[^\"]*\"", r"\1", text)
    text = re.sub(r"(<svg\b[^>]*?)\s(width|height)=\"[^\"]*\"", r"\1", text)
    return text.strip()


