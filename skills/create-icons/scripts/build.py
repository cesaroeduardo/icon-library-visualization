def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", help="icons.json")
    ap.add_argument("--out", required=True, help="output directory (or .html file with --gallery)")
    ap.add_argument("--framework", choices=FRAMEWORKS)
    ap.add_argument("--name", help="package name (default: source package.name)")
    ap.add_argument("--only", help="comma-separated icon names to rewrite; aggregates are always rebuilt")
    ap.add_argument("--compare", help="directory of the project's current SVG icons to show side by side")
    ap.add_argument("--catalog-only", action="store_true", help="write only catalog.html (for samples)")
    ap.add_argument("--gallery", nargs="+", help="build one page comparing several sources")
    args = ap.parse_args(argv)

    if args.gallery:
        write(os.path.abspath(args.out), build_gallery(args.gallery))
        print("gallery: %s" % os.path.abspath(args.out))
        return 0
    if not args.source:
        ap.error("source is required")
    try:
        src, style = load_source(args.source)
        icons = flat_icons(src)
        if not icons:
            raise SourceError("the source has no icons")
        out = os.path.abspath(args.out)
        if args.catalog_only:
            write(os.path.join(out, "catalog.html"), build_catalog(src, style, icons, args.compare))
            print("catalog: %s" % os.path.join(out, "catalog.html"))
            return 0
        framework = args.framework or src.get("framework") or "react"
        name = args.name or (src.get("package") or {}).get("name") or "icons"
        only = set(filter(None, (args.only or "").split(",")))
        unknown = only - {i["name"] for i in icons}
        if unknown:
            raise SourceError("--only names not in the source: %s" % ", ".join(sorted(unknown)))
        targets = [i for i in icons if not only or i["name"] in only]
        ext = GENERATORS[framework](targets, style, out) or "svg"
        for icon in targets:
            write(os.path.join(out, "svg", icon["name"] + ".svg"), svg_document(icon, style, "hex"))
        gen_index(icons, out, framework, ext)
        gen_package_json(src, style, out, framework, ext, name)
        write(os.path.join(out, "icons.css"), build_css(style))
        write(os.path.join(out, "sprite.svg"), '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">%s</svg>\n'
              % "".join(build_sprite(icons, style)))
        write(os.path.join(out, "manifest.json"), json.dumps({
            "name": name, "style": style.get("name"), "framework": framework, "grid": style["grid"],
            "icons": [{"name": i["name"], "label": i["label"], "group": i["group"], "tags": i.get("tags", []),
                       "component": component_name(i["name"])} for i in icons]}, indent=2, ensure_ascii=False) + "\n")
        prefix = style.get("prefix") or "ic"
        catalog_entries = []
        for i in icons:
            kw_parts = []
            raw_kw = i.get("keywords")
            if isinstance(raw_kw, str):
                kw_parts.extend(raw_kw.replace(",", " ").split())
            elif isinstance(raw_kw, list):
                kw_parts.extend(str(x) for x in raw_kw)
            for tag in i.get("tags", []):
                kw_parts.append(str(tag))
            if i.get("label"):
                kw_parts.append(str(i["label"]))
            if i.get("group"):
                kw_parts.append(str(i["group"]))
            seen = set()
            deduped = []
            for w in kw_parts:
                wl = w.strip().lower()
                if wl and wl not in seen:
                    seen.add(wl)
                    deduped.append(w.strip())
            catalog_entries.append({
                "name": i["name"],
                "icon": "%s %s" % (prefix, i["name"]),
                "label": i.get("label") or i["name"],
                "group": i.get("group") or "",
                "keywords": " ".join(deduped),
            })
        write(os.path.join(out, "catalog.json"), json.dumps(catalog_entries, indent=2, ensure_ascii=False) + "\n")
        write(os.path.join(out, "catalog.html"), build_catalog(src, style, icons, args.compare))
        write(os.path.join(out, "README.md"), build_readme(src, style, icons, framework, name))
        print("built %d icon(s) (%s) into %s" % (len(targets), framework, out))
        print("catalog: %s" % os.path.join(out, "catalog.html"))
        return 0
    except (SourceError, KeyError, ValueError, OSError) as exc:
        print("error: %s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
